#!/usr/bin/env python3
"""
The three launch rails without their pylons, cut out of the meshes that carry them.

    ./tools/model/bare-rails.py           # write src/KSArmory/Meshes/KSArmory_BareRails.glb
    ./tools/model/bare-rails.py --check   # fail if that file is not what the sources give

Every rail ships with its pylon modelled in, so hung under the suspension rail it reads as two
pylons. Each source mesh is a set of closed boxes, and the pylon's boxes all start nearer the
mounting face than the rail's do, so a rail is the components that begin at or beyond `CUT`. The
kept mesh is moved so the rail's own top is the new mounting face, at X = 0.

Derived rather than re-modelled: the LAU-7 is generated by sidewinder.py and the other two are
authored exports whose .blend is not in this repository. Rerun this after either changes.

Needs neither Blender nor the game. The UVs, and so the textures, are the source's.
"""

import argparse
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MESHES = ROOT / "src" / "KSArmory" / "Meshes"
OUT = MESHES / "KSArmory_BareRails.glb"

# bare mesh -> (source atlas, source mesh, CUT): a component is kept when its nearest point to the
# mounting face is at or beyond CUT, in metres along +X.
RAILS = {
    "KSArmory_Subpart_Lau7": ("KSArmory_MeshAtlas.glb", "KSArmory_Subpart_SidewinderRail", 0.17),
    "KSArmory_Subpart_Lau128": ("KSArmory_Amraam.glb", "KSArmory_Subpart_AmraamRail", 0.186),
    "KSArmory_Subpart_Lau118": ("KSArmory_Harm.glb", "KSArmory_Subpart_HarmRail", 0.19),
}

_COMPONENTS = {5126: ("f", 4), 5125: ("I", 4), 5123: ("H", 2), 5121: ("B", 1)}
_WIDTH = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4}


def read_glb(path):
    data = path.read_bytes()
    json_len = struct.unpack_from("<I", data, 12)[0]
    gltf = json.loads(data[20:20 + json_len])
    offset = 20 + json_len
    bin_len = struct.unpack_from("<I", data, offset)[0]
    return gltf, data[offset + 8:offset + 8 + bin_len]


def accessor(gltf, binary, index):
    acc = gltf["accessors"][index]
    view = gltf["bufferViews"][acc["bufferView"]]
    fmt, size = _COMPONENTS[acc["componentType"]]
    width = _WIDTH[acc["type"]]
    stride = view.get("byteStride", size * width)
    base = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
    return [struct.unpack_from("<" + fmt * width, binary, base + k * stride) for k in range(acc["count"])]


def primitive(gltf, binary, mesh_name):
    for mesh in gltf["meshes"]:
        if mesh["name"] == mesh_name:
            if len(mesh["primitives"]) != 1:
                sys.exit(f"{mesh_name}: expected one primitive, found {len(mesh['primitives'])}")
            prim = mesh["primitives"][0]
            attributes = {name: accessor(gltf, binary, i) for name, i in sorted(prim["attributes"].items())}
            return attributes, [t[0] for t in accessor(gltf, binary, prim["indices"])]
    sys.exit(f"no mesh {mesh_name}")


def components(positions, indices):
    """Vertex groups joined by a triangle or by sharing a position -- a split normal is one surface."""
    parent = list(range(len(positions)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    seen = {}
    for i, p in enumerate(positions):
        key = tuple(round(c, 5) for c in p)
        if key in seen:
            parent[find(i)] = find(seen[key])
        else:
            seen[key] = i
    for t in range(0, len(indices), 3):
        a, b, c = indices[t:t + 3]
        parent[find(b)] = find(a)
        parent[find(c)] = find(a)
    groups = {}
    for i in range(len(positions)):
        groups.setdefault(find(i), []).append(i)
    return list(groups.values())


def cut(attributes, indices, threshold):
    """The rail's triangles, compacted and moved so the rail's top sits on X = 0. Returns the shift too."""
    positions = attributes["POSITION"]
    keep = set()
    for group in components(positions, indices):
        if min(positions[i][0] for i in group) >= threshold:
            keep.update(group)
    if not keep:
        sys.exit("nothing left beyond the cut")
    shift = min(positions[i][0] for i in keep)

    remap = {old: new for new, old in enumerate(sorted(keep))}
    out = {name: [values[old] for old in sorted(keep)] for name, values in attributes.items()}
    out["POSITION"] = [(p[0] - shift, p[1], p[2]) for p in out["POSITION"]]
    triangles = []
    for t in range(0, len(indices), 3):
        tri = indices[t:t + 3]
        if all(v in remap for v in tri):
            triangles += [remap[v] for v in tri]
        elif any(v in remap for v in tri):
            sys.exit("a triangle spans the cut")
    return out, triangles, shift


def build():
    """The bare atlas as bytes, and each rail's shift: how far its new mounting face is from the old."""
    gltf = {"asset": {"version": "2.0", "generator": "tools/model/bare-rails.py"},
            "scene": 0, "scenes": [{"nodes": []}], "nodes": [], "meshes": [],
            "accessors": [], "bufferViews": [], "buffers": []}
    blob = bytearray()
    shifts = {}

    def add_view(payload, target):
        while len(blob) % 4:
            blob.append(0)
        gltf["bufferViews"].append({"buffer": 0, "byteOffset": len(blob), "byteLength": len(payload),
                                    "target": target})
        blob.extend(payload)
        return len(gltf["bufferViews"]) - 1

    def add_vectors(values, kind):
        width = _WIDTH[kind]
        payload = b"".join(struct.pack("<" + "f" * width, *v) for v in values)
        entry = {"bufferView": add_view(payload, 34962), "componentType": 5126,
                 "count": len(values), "type": kind}
        if kind == "VEC3":
            entry["min"] = [min(v[k] for v in values) for k in range(3)]
            entry["max"] = [max(v[k] for v in values) for k in range(3)]
        gltf["accessors"].append(entry)
        return len(gltf["accessors"]) - 1

    sources = {}
    for name, (atlas, source, threshold) in RAILS.items():
        if atlas not in sources:
            sources[atlas] = read_glb(MESHES / atlas)
        source_gltf, binary = sources[atlas]
        for suffix in ("", "_VM"):
            attributes, indices = primitive(source_gltf, binary, source + suffix)
            kept, triangles, shift = cut(attributes, indices, threshold)
            if shifts.setdefault(name, shift) != shift:
                sys.exit(f"{source}_VM is cut at {shift}, its model at {shifts[name]}")

            kinds = {"POSITION": "VEC3", "NORMAL": "VEC3", "TEXCOORD_0": "VEC2"}
            prim_attributes = {attr: add_vectors(kept[attr], kinds[attr]) for attr in sorted(kept)}
            payload = b"".join(struct.pack("<I", i) for i in triangles)
            gltf["accessors"].append({"bufferView": add_view(payload, 34963), "componentType": 5125,
                                      "count": len(triangles), "type": "SCALAR"})
            gltf["meshes"].append({"name": name + suffix, "primitives": [
                {"attributes": prim_attributes, "indices": len(gltf["accessors"]) - 1}]})
            gltf["nodes"].append({"name": name + suffix, "mesh": len(gltf["meshes"]) - 1})
            gltf["scenes"][0]["nodes"].append(len(gltf["nodes"]) - 1)

    while len(blob) % 4:
        blob.append(0)
    gltf["buffers"].append({"byteLength": len(blob)})
    text = json.dumps(gltf, separators=(",", ":")).encode()
    text += b" " * (-len(text) % 4)
    total = 12 + 8 + len(text) + 8 + len(blob)
    data = (struct.pack("<III", 0x46546C67, 2, total) + struct.pack("<II", len(text), 0x4E4F534A) + text
            + struct.pack("<II", len(blob), 0x004E4942) + bytes(blob))
    return data, shifts


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args()

    data, shifts = build()
    if args.check:
        if not OUT.is_file() or OUT.read_bytes() != data:
            print(f"bare-rails: {OUT.relative_to(ROOT)} is stale -- run tools/model/bare-rails.py",
                  file=sys.stderr)
            return 1
        print(f"bare-rails: {len(RAILS)} rails match their sources")
        return 0

    OUT.write_bytes(data)
    for name, shift in shifts.items():
        print(f"{name}: mounting face {shift:.5f} m out of the source's")
    return 0


if __name__ == "__main__":
    sys.exit(main())
